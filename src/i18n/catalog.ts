export type UiLocale = "en" | "nl";
export type MessageKey = keyof typeof en;
export type MessageParameters = Record<string, string | number>;
export type MessageTranslator = (
  message: string | MessageDescriptor,
  params?: MessageParameters,
) => string;

export const DUTCH_CATALOG_STATUS = "draft";
export const MESSAGE_CATALOGS: Record<UiLocale, Record<MessageKey, string>> = { en, nl };

export function uiLocaleForExplanationLanguage(language: "en" | "nl" | "fa"): UiLocale {
  return language === "fa" ? "en" : language;
}

export function formatMessage(
  locale: UiLocale,
  key: string,
  params: MessageParameters = {},
): string {
  const template = MESSAGE_CATALOGS[locale][key as MessageKey];
  if (template === undefined) throw new Error(`Unknown message key: ${key}`);
  return template.replace(/\{([a-zA-Z0-9_]+)\}/gu, (_match, name: string) => {
    const value = params[name];
    if (value === undefined) throw new Error(`Missing message parameter "${name}" for ${key}.`);
    return String(value);
  });
}
